    private static String classNames(ClassCategory category, boolean includeInitial) {
        return ClassDefinitions.byCategory(category).stream()
                .filter(definition -> includeInitial || !isInitialClass(definition.classKey()))
                .map(definition -> definition.name().getString())
                .reduce((left, right) -> left + ", " + right)
                .orElse("—");
    }

    private static boolean isInitialClass(String classKey) {
        return "stormtrooper".equals(classKey)
                || "sniper".equals(classKey)
                || "scout".equals(classKey);
    }

    private static Block title(String text) {
        return new Block(BlockStyle.TITLE, Component.literal(text));
    }

    private static Block heading(String text) {
        return new Block(BlockStyle.HEADING, Component.literal(text));
    }

    private static Block body(String text) {
        return new Block(BlockStyle.BODY, Component.literal(text));
    }

    private static Block bullet(String text) {
        return new Block(BlockStyle.BULLET, Component.literal("• " + text));
    }

    private static Block warning(String text) {
        return new Block(BlockStyle.WARNING, Component.literal(text));
    }
